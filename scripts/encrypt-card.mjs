/**
 * 加密名片明文 → 生成 src/data/businessCard.ts 的密文常量。
 *
 * 用法：
 *   CARD_PASSWORD=你的口令 node scripts/encrypt-card.mjs
 *
 * 算法：PBKDF2(SHA-256, 150000) 派生 AES-GCM 256 密钥，随机 salt + iv。
 * 输出格式：base64(salt).base64(iv).base64(ciphertext)
 * 明文来自 scripts/.card-secret.json（已被 .gitignore 忽略，不会进仓库）。
 */
import { webcrypto as crypto } from 'node:crypto';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const b64 = (buf) => Buffer.from(buf).toString('base64');

const password = process.env.CARD_PASSWORD;
if (!password) {
  console.error('❌ 请通过环境变量 CARD_PASSWORD 传入口令，例如：');
  console.error('   CARD_PASSWORD=你的口令 node scripts/encrypt-card.mjs');
  process.exit(1);
}

const secretPath = resolve(__dirname, '.card-secret.json');
const outPath = resolve(__dirname, '../src/data/businessCard.ts');

const raw = fs.readFileSync(secretPath, 'utf8');
const data = JSON.parse(raw);
data._check = 'bobcard-v1';

const enc = new TextEncoder();
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));

const keyMaterial = await crypto.subtle.importKey(
  'raw',
  enc.encode(password),
  'PBKDF2',
  false,
  ['deriveKey'],
);
const key = await crypto.subtle.deriveKey(
  { name: 'PBKDF2', salt, iterations: 150_000, hash: 'SHA-256' },
  keyMaterial,
  { name: 'AES-GCM', length: 256 },
  false,
  ['encrypt'],
);

const ciphertext = await crypto.subtle.encrypt(
  { name: 'AES-GCM', iv },
  key,
  enc.encode(JSON.stringify(data)),
);

const payload = `${b64(salt)}.${b64(iv)}.${b64(new Uint8Array(ciphertext))}`;

const out = `// AUTO-GENERATED by scripts/encrypt-card.mjs —— 请勿手动修改。
// 明文见 scripts/.card-secret.json（已被 .gitignore 忽略，不会进入源码 / 仓库）。
// 重新生成：先修改 .card-secret.json，再 \`CARD_PASSWORD=你的口令 npm run gen:card\`。
// 口令只存在于你的脑中，不写进源码、不进入构建产物；输入正确口令才能解密本密文。

export const BUSINESS_CARD_CIPHERTEXT = '${payload}';
`;

fs.writeFileSync(outPath, out);
console.log('✅ 已写入', outPath);
console.log('   密文长度', payload.length, '字符');
